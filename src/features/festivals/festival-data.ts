export interface FestivalInfo {
  id: FestivalId
  name: string
  /** Other names, shown under the title. */
  alt?: string
  /** The festive salutation: "Shubh Deepavali". */
  salutation: string
  /** Shown on screen; Windows cannot draw flag emoji, so the national days use 🎉 here. */
  emoji: string
  /** Used in greetings that are shared to phones, where a flag shows properly. */
  shareEmoji?: string
  theme: ThemeKey
  /** Big enough for the automatic full-screen celebration (the admin can change it). */
  major: boolean
  /** Wins when two festivals share a day; higher first. */
  priority: number
  /** How its date is set in the Panchang. */
  panchang: string
  regions: string
  /** The same day elsewhere in India. */
  regional?: string[]
  about: string
  traditions: string[]
  facts: string[]
  /** One-line wishes for greetings. */
  wishes: string[]
  /** What Robi says when you open him that day; {name} is your first name. */
  robi: string[]
  /** Words that name it in a chat message. */
  aliases: string[]
  /** Words that name it only on or near its day ("happy new year"). */
  nearAliases?: string[]
  /** A fixed calendar date (the national days), month 1-12. */
  fixed?: { month: number; day: number }
  /** Celebrate on every day of a multi-day festival (nine nights of garba), not just the first. */
  everyDay?: boolean
}

